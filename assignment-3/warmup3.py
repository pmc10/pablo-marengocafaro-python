# Boolean expression

# Expression 1 Prints: False
print(not True and False)  

# Expression 2 Prints: True
print(True or False and False)   

# Expression 3 Prints: False
print(not (5 > 3))  

# Expression 4 Prints: False
print(10 == 10 and 4 != 4)  

# Expression 5 Prints: True
print(not False or not True)  